function getSeasonalTips()
{
    $season = date('n');
    if ($season >= 3 && $season <= 5) return 'Весной актуальны экологические темы и субботники';
    if ($season >= 6 && $season <= 8) return 'Летом проводите мероприятия на свежем воздухе';
    if ($season >= 9 && $season <= 11) return 'Осенью сделайте акцент на новых знаниях';
    return 'Зимой создавайте уютную атмосферу, добавьте чаепитие';
}


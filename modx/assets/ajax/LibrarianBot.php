function generateExpandedResult($session, $knowledgeBase)
{
    $mode = $session['mode'];
    $answers = $session['answers'];

    if ($mode === 'planner') {
        return generatePlan($answers, $knowledgeBase);
    } elseif ($mode === 'expert') {
        return evaluateExpert($answers, $session['questions']);
    } else {
        return constructFormat($answers, $knowledgeBase);
    }
}

function generatePlan($answers, $kb) {
    $theme = $answers['theme'] ?? 'Мероприятие';
    $audienceKey = $answers['audience'] ?? 'adults';
    $goal = $answers['goal'] ?? 'education';
    $formatPref = $answers['format_preference'] ?? 'mixed';
    $duration = $answers['duration'] ?? '1hour';
    $resources = $answers['resources'] ?? [];
    if (is_string($resources)) {
        $resources = json_decode($resources, true);
        if (!is_array($resources)) {
            $resources = [];
        }
    }

    $audience = $kb['audiences'][$audienceKey];

    // Подбираем форматы
    $recommendedFormats = [];
    if ($formatPref === 'active') {
        $recommendedFormats = ['quest', 'quiz'];
    } elseif ($formatPref === 'intellectual') {
        $recommendedFormats = ['lecture', 'discussion'];
    } elseif ($formatPref === 'creative') {
        $recommendedFormats = ['masterclass'];
    } else {
        $recommendedFormats = ['quest', 'lecture', 'masterclass'];
    }

    $formatsList = [];
    foreach ($recommendedFormats as $f) {
        if (isset($kb['formats'][$f])) {
            $formatsList[] = $kb['formats'][$f]['name'];
        }
    }

    // Структура мероприятия
    $structure = [
        'Вступление (5-10 мин) - приветствие, объяснение темы',
        'Основная часть (' . ($duration === '30min' ? '20-25 мин' : ($duration === '1hour' ? '40-45 мин' : '60-90 мин')) . ') - основное содержание',
        'Интерактив (' . ($duration === '30min' ? '5 мин' : '10-15 мин') . ') - вовлечение участников',
        'Заключение (5-10 мин) - подведение итогов, ответы на вопросы'
    ];

    // Чек-лист
    $checklist = [
        'Подготовить сценарий мероприятия',
        'Подобрать необходимые материалы и реквизит',
        'Протестировать оборудование',
        'Сделать анонс в соцсетях и на сайте',
        'Подготовить раздаточные материалы',
        'Организовать фото- и видеосъёмку',
        'Продумать систему обратной связи'
    ];

    // Добавляем специфичные пункты
    if (in_array('craft', $resources)) {
        $checklist[] = 'Закупить материалы для творчества';
    }
    if (in_array('volunteers', $resources)) {
        $checklist[] = 'Провести инструктаж с волонтёрами';
    }

    return [
        'type' => 'plan',
        'title' => $theme,
        'audience' => $audience['name'],
        'goal' => getGoalText($goal),
        'duration' => getDurationText($duration),
        'recommended_formats' => implode(', ', $formatsList),
        'age_features' => $audience['age_features'],
        'structure' => $structure,
        'recommendations' => $audience['tips'],
        'checklist' => $checklist,
        'seasonal_tips' => getSeasonalTips(),
        'pros_cons' => getProsCons($recommendedFormats[0], $kb)
    ];
}

function evaluateEvent($answers, $kb)
{
    $plan = $answers['plan'] ?? '';
    $audienceKey = $answers['audience'] ?? 'adults';
    $count = $answers['expected_count'] ?? 'medium';
    $resources = $answers['resources_available'] ?? [];

    $audience = $kb['audiences'][$audienceKey];

    $score = 70; // Базовая оценка
    $strengths = [];
    $weaknesses = [];
    $recommendations = [];

    // Оценка по аудитории
    $strengths[] = "Учтена целевая аудитория: {$audience['name']}";
    $recommendations[] = "Обязательно учтите возрастные особенности: {$audience['age_features']}";

    // Оценка по количеству
    if ($count === 'mass') {
        $weaknesses[] = "Для большого количества участников потребуется усиленная команда и оборудование";
        $recommendations[] = "Привлеките волонтёров для помощи";
    } elseif ($count === 'small') {
        $strengths[] = "Небольшая группа позволит уделить внимание каждому участнику";
    }

    // Оценка ресурсов
    if (in_array('projector', $resources)) {
        $strengths[] = "Наличие проектора позволит использовать визуальные материалы";
    } else {
        $weaknesses[] = "Отсутствие проектора ограничивает визуальное сопровождение";
        $recommendations[] = "Используйте печатные материалы или флипчарт";
    }

    if (!in_array('volunteers', $resources) && $count !== 'small') {
        $recommendations[] = "Рекомендуем привлечь помощников для проведения мероприятия";
    }

    return [
        'type' => 'evaluation',
        'score' => $score,
        'strengths' => $strengths,
        'weaknesses' => $weaknesses,
        'recommendations' => $recommendations,
        'next_steps' => [
            'Доработать сценарий с учётом рекомендаций',
            'Провести техническую репетицию',
            'Подготовить резервный план на случай форс-мажора'
        ]
    ];
}

// Функция для режима "Эксперт"
function evaluateExpert($answers, $questions)
{
    $advices = [];

    // Собираем советы по вопросам, где ответили "нет"
    foreach ($questions as $question) {
        $qid = $question['id'];
        $answer = $answers[$qid] ?? '';

        // Если ответ "нет" или "false"
        if ($answer === 'false' || $answer === 'no' || $answer === 'нет' || $answer === false) {
            if (!empty($question['advice'])) {
                $advices[] = $question['advice'];
            }
        }
    }

    // Общие советы для всех случаев
    $generalAdvices = [
        'Согласование. Малоизвестных авторов и спорные темы предварительно согласуйте с директором или заместителем директора.',
        'Подготовка к мероприятию. Используйте только проверенные источники. Если источник вызывает сомнение, посоветуйтесь с библиографами.',
        'Форс-мажор. Предупреждайте коллег из методического отдела об отмене или переносе мероприятия.',
        'Внешний вид и отношение. Вы — лицо библиотеки. Опрятный внешний вид, доброжелательность, готовность помочь и улыбка создают ту самую атмосферу.',
        'Порядок в библиотеке. Чистота и уют — это то, что посетители ценят не меньше, чем интересную программу.',
        'Обратная связь. После мероприятия собирайте отзывы. Это нужно для понимания: что получилось, что исправить, придут ли эти люди снова.'
    ];

    $result = [
        'type' => 'expert',
        'has_issues' => count($advices) > 0,
        'advices' => $advices,
        'general_advices' => $generalAdvices
    ];

    return $result;
}

